class Command(BaseCommand):
    help = "Seed Grades (1–12) and their Subjects"

    def handle(self, *args, **kwargs):
        for grade_number, subjects in GRADE_SUBJECTS.items():
            grade, created = Grade.objects.get_or_create(number=grade_number)
            if created:
                self.stdout.write(self.style.SUCCESS(f"Grade {grade_number} үүсгэгдлээ"))

            for subject_name in subjects:
                subject, sub_created = Subject.objects.get_or_create(name=subject_name, grade=grade)
                if sub_created:
                    self.stdout.write(self.style.SUCCESS(f"  Subject '{subject_name}' үүсгэгдлээ"))
        self.stdout.write(self.style.SUCCESS("Бүх Grade болон Subject-ууд амжилттай үүсгэгдлээ!"))
